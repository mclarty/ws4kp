// Immediate WeatherStar-style interrupt for NWS warnings.
// Original 4000 behavior: attention tone, full-screen red vertical scroll,
// then a red lower-display-line crawl for the remainder of the warning.

import getHazards from './hazards.mjs';
import settings from './settings.mjs';
import { debugFlag } from './utils/debug.mjs';

const POLL_MS = 15_000;
const SCROLL_PX_PER_SEC = 42;
const WARNING_EVENT_RE = /warning$/i;
const WATCH_EVENT_RE = /watch$/i;

const DEMO_ALERT = {
	id: 'demo-tornado-warning',
	properties: {
		event: 'Tornado Warning',
		severity: 'Extreme',
		urgency: 'Immediate',
		certainty: 'Observed',
		headline: 'Tornado Warning issued for this location',
		description: 'THE NATIONAL WEATHER SERVICE HAS ISSUED A TORNADO WARNING FOR THIS AREA.\n\nA SEVERE THUNDERSTORM CAPABLE OF PRODUCING A TORNADO WAS LOCATED NEAR THIS LOCATION, MOVING NORTHEAST AT 35 MPH.\n\nHAZARD...TORNADO AND QUARTER SIZE HAIL.\n\nSOURCE...RADAR INDICATED ROTATION.\n\nIMPACT...FLYING DEBRIS WILL BE DANGEROUS TO THOSE CAUGHT WITHOUT SHELTER. MOBILE HOMES WILL BE DAMAGED OR DESTROYED. DAMAGE TO ROOFS, WINDOWS, AND VEHICLES WILL OCCUR. TREE DAMAGE IS LIKELY.\n\nTHIS IS A DEMONSTRATION ALERT GENERATED BY WEATHERSTAR 4000+ BREAK-IN MODE. IT IS NOT A REAL NATIONAL WEATHER SERVICE WARNING.',
		instruction: 'TAKE COVER NOW. MOVE TO A BASEMENT OR AN INTERIOR ROOM ON THE LOWEST FLOOR OF A STURDY BUILDING.',
	},
};

let overlay;
let overlayEvent;
let overlayText;
let lastSeenIds = new Set();
let announcedIds = new Set();
let activeWarnings = [];
let overlayTimer = null;
let overlayRaf = null;
let overlayActive = false;
let started = false;

const isWarning = (alert) => {
	const event = alert?.properties?.event ?? '';
	const severity = alert?.properties?.severity ?? '';
	return WARNING_EVENT_RE.test(event) || severity === 'Extreme';
};

const isWatch = (alert) => WATCH_EVENT_RE.test(alert?.properties?.event ?? '');

const formatBulletin = (alert) => {
	const p = alert.properties ?? {};
	const parts = [
		(p.event ?? 'WEATHER WARNING').toUpperCase(),
		p.headline,
		p.description,
		p.instruction,
	].filter(Boolean);
	return parts
		.join('\n\n')
		.replaceAll('\n\n', '\n \n')
		.replaceAll('\n', ' ')
		.replace(/\s+/g, ' ')
		.trim();
};

const playAttentionTone = () => {
	try {
		const Ctx = window.AudioContext || window.webkitAudioContext;
		if (!Ctx) return;
		const ctx = new Ctx();
		const beep = (freq, start, dur) => {
			const osc = ctx.createOscillator();
			const gain = ctx.createGain();
			osc.type = 'square';
			osc.frequency.value = freq;
			gain.gain.setValueAtTime(0.0001, ctx.currentTime + start);
			gain.gain.exponentialRampToValueAtTime(0.12, ctx.currentTime + start + 0.02);
			gain.gain.exponentialRampToValueAtTime(0.0001, ctx.currentTime + start + dur);
			osc.connect(gain);
			gain.connect(ctx.destination);
			osc.start(ctx.currentTime + start);
			osc.stop(ctx.currentTime + start + dur + 0.05);
		};
		// Two-tone attention signal reminiscent of the STAR alert leader.
		beep(880, 0.00, 0.28);
		beep(698, 0.36, 0.28);
		beep(880, 0.72, 0.40);
		setTimeout(() => ctx.close().catch(() => {}), 1600);
	} catch (error) {
		if (debugFlag('verbose-failures')) {
			console.warn('Unable to play warning tone', error);
		}
	}
};

const hideOverlay = () => {
	if (overlayRaf) {
		cancelAnimationFrame(overlayRaf);
		overlayRaf = null;
	}
	if (overlayTimer) {
		clearTimeout(overlayTimer);
		overlayTimer = null;
	}
	overlayActive = false;
	overlay?.classList.remove('show');
	document.getElementById('container')?.classList.remove('breakin-active');
};

const showOverlay = (alert) => {
	if (!overlay || overlayActive) return;
	overlayActive = true;
	overlayEvent.textContent = (alert.properties?.event ?? 'WEATHER WARNING').toUpperCase();
	overlayText.textContent = formatBulletin(alert);
	overlayText.style.transform = 'translateY(0px)';
	overlay.classList.add('show');
	document.getElementById('container')?.classList.add('breakin-active');
	playAttentionTone();

	// Allow a paint so heights are measurable, then scroll the bulletin off.
	requestAnimationFrame(() => {
		const windowEl = overlay.querySelector('.breakin-scroll-window');
		const textHeight = overlayText.scrollHeight;
		const viewHeight = windowEl?.clientHeight ?? 320;
		const distance = Math.max(0, textHeight - viewHeight + 24);
		const durationMs = Math.max(8000, (distance / SCROLL_PX_PER_SEC) * 1000) / (settings.speed?.value || 1);

		const startedAt = performance.now();
		const tick = (now) => {
			const t = Math.min(1, (now - startedAt) / durationMs);
			overlayText.style.transform = `translateY(-${Math.round(distance * t)}px)`;
			if (t < 1 && overlayActive) {
				overlayRaf = requestAnimationFrame(tick);
			} else {
				overlayTimer = setTimeout(hideOverlay, 1800);
			}
		};
		overlayRaf = requestAnimationFrame(tick);
	});
};

const applyCrawlState = () => {
	const scroll = document.querySelector('#container>.scroll');
	if (!scroll) return;
	if (activeWarnings.length > 0) {
		scroll.classList.add('hazard', 'warning-breakin');
	} else {
		scroll.classList.remove('warning-breakin');
	}
};

const evaluateAlerts = (alerts = []) => {
	if (settings.warningBreakIn && settings.warningBreakIn.value === false) {
		activeWarnings = [];
		applyCrawlState();
		return;
	}

	const warnings = alerts.filter(isWarning);
	activeWarnings = warnings;

	const newWarnings = warnings.filter((alert) => !announcedIds.has(alert.id));
	if (newWarnings.length > 0) {
		newWarnings.forEach((alert) => announcedIds.add(alert.id));
		showOverlay(newWarnings[0]);
	}

	// Drop IDs that are no longer active so a reissue can break in again later.
	const liveIds = new Set(alerts.map((alert) => alert.id));
	announcedIds = new Set([...announcedIds].filter((id) => liveIds.has(id) || id.startsWith('demo-')));
	lastSeenIds = liveIds;
	applyCrawlState();
};

const poll = async () => {
	try {
		const params = new URLSearchParams(window.location.search);
		if (params.get('demoWarning') === 'true') {
			evaluateAlerts([DEMO_ALERT]);
			return;
		}
		const alerts = await getHazards();
		evaluateAlerts(Array.isArray(alerts) ? alerts : []);
	} catch (error) {
		if (debugFlag('verbose-failures')) {
			console.warn('Severe weather break-in poll failed', error);
		}
	}
};

const bindDom = () => {
	overlay = document.getElementById('severe-weather-breakin');
	overlayEvent = overlay?.querySelector('.breakin-event');
	overlayText = overlay?.querySelector('.breakin-text');
};

const start = () => {
	if (started) return;
	started = true;
	bindDom();
	window.addEventListener('ws4kp-hazards', (event) => {
		evaluateAlerts(event.detail?.alerts ?? []);
	});
	poll();
	setInterval(poll, POLL_MS);
};

document.addEventListener('DOMContentLoaded', start);

window.SevereWeatherBreakIn = {
	isWarning,
	isWatch,
	getActiveWarnings: () => activeWarnings,
	getCrawlText: () => {
		if (activeWarnings.length === 0) return null;
		return activeWarnings
			.map((alert) => `${alert.properties.event} ... ${formatBulletin(alert)}`)
			.join('     ');
	},
	demo: () => evaluateAlerts([DEMO_ALERT]),
	hideOverlay,
};

export {
	isWarning,
	isWatch,
	formatBulletin,
};
